#!/bin/sh
# Regenerates tests/fuzz/econ.dict: every JSON key and short string the protocol reads or
# writes (the quoted identifiers in Protocol.cpp, Chat.cpp, Events.cpp), plus the JSON
# tokens a mutation needs to build structure. Run from the repository root.
set -eu
out=tests/fuzz/econ.dict
{
    echo '# libFuzzer dictionary for the econspace wire (#518). Generated by gen_dict.sh.'
    echo '# JSON tokens'
    for t in '{' '}' '[' ']' ':' ',' 'true' 'false' 'null' '-1' '0' '1' '1e308' '-1e308' \
             '4294967296' '9223372036854775807' '18446744073709551615' '0.5'; do
        printf '"%s"\n' "$t"
    done
    echo '# protocol keys and words'
    cat src/game/sim/Protocol.cpp src/game/sim/Chat.cpp src/game/sim/Events.cpp \
        | grep -oE '"[A-Za-z_][A-Za-z0-9_]{0,30}"' | sort -u
} > "$out"
