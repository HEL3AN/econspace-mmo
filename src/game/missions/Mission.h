#pragma once

#include "economy/Resource.h"
#include "core/Faction.h"
#include <string>

class Station;

// Mission type. The objective and how it's completed depend on the type.
enum class MissionType
{
    Bounty,    // destroy N pirates
    Mining,    // mine and deliver N units of a resource
    Delivery,  // deliver cargo to another station
    // Jobs a faction's plan posts (#345): the living world's work, paid out of its stock.
    Supply,  // deliver N of a good to a site going up, which then goes up faster
    Escort,  // fly with a builder convoy to its site
    Siege,   // break a siege: shoot down N of the besiegers' warships
};

// Whether a mission is a plan's job (#345): handed in anywhere -- the faction pays by wire --
// and over when the plan is.
inline bool IsPlanJob(MissionType t)
{
    return t == MissionType::Supply || t == MissionType::Escort || t == MissionType::Siege;
}

// A single mission. Generated by the issuing station from a template; once
// accepted it lands in the player's active mission log.
struct Mission
{
    MissionType type = MissionType::Bounty;
    FactionId   faction = Factions::Unaffiliated();  // issuer (the station's faction)
    std::string title;                               // short heading for lists
    std::string description;                         // what needs to be done

    // Stations by stable id (Entity::GetId), not by pointer: a mission must
    // survive the network (the client has no live server objects) and saving (M4f-2).
    int giverStationId = 0;  // issuing station (turn in Bounty/Mining here)
    int destStationId = 0;   // destination station (for Delivery)

    ResourceType resource;         // what to mine (for Mining)
    int          targetCount = 0;  // how much to mine / kill
    int          progress = 0;     // current progress (pirate kill counter)

    double rewardMoney = 0.0;
    float  rewardRep = 0.0f;

    // --- A plan's job (#345) ---
    // The plan, by its id (stable: plans are saved with it), and the system it is about --
    // the site's, the convoy's destination, the outpost under siege -- with that system's name,
    // since the client sees only its own. A job not done by `deadline` (world time) is failed.
    int         planId = 0;
    std::string systemId;
    std::string systemName;
    double      deadline = 0.0;
    // An escort's: which of the plan's convoys it is with (a lost one is a setback, and the
    // next is another job), and whether the pilot has been with it yet.
    int  stage = 0;
    bool rode = false;

    // Transient (not saved): whether it can be turned in right now. Over the
    // network the server computes it and puts it in the snapshot (the client field
    // is a mirror, not always accurate locally).
    bool completable = false;
};
